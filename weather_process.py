# 5. CSV 파일 목록 가져오기
# ============================================================

csv_files = []

for file in input_folder.glob("*.csv"):

    # --------------------------------------------------------
    # Excel 임시파일 제외
    # 예:
    # ~$SURFACE_AWS_400...
    # --------------------------------------------------------

    if file.name.startswith("~$"):
        continue

    # --------------------------------------------------------
    # 이전 실행에서 생성한 결과파일 제외
    # --------------------------------------------------------

    if file.name == output_file.name:
        continue

    csv_files.append(file)


print("=" * 70)
print(f"처리할 CSV 파일 수: {len(csv_files)}개")
print("=" * 70)


# ============================================================
# 6. 결과를 담을 리스트
# ============================================================

result_list = []

success_count = 0
fail_count = 0


# ============================================================
# 7. 각 CSV 파일 처리
# ============================================================

for file in csv_files:

    print()
    print(f"처리 중: {file.name}")


    # --------------------------------------------------------
    # CSV 읽기
    # --------------------------------------------------------

    try:

        df = read_csv_auto(file)

    except Exception as e:

        print(
            f"  -> 읽기 실패: {e}"
        )

        fail_count += 1

        continue


    # --------------------------------------------------------
    # 컬럼명 자동 인식
    # --------------------------------------------------------

    original_columns = df.columns.tolist()

    df = normalize_columns(df)


    # --------------------------------------------------------
    # 필요한 컬럼 확인
    # --------------------------------------------------------

    required_columns = [
        "지점",
        "일시",
        "기온",
        "풍속",
        "습도"
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in df.columns
    ]


    # --------------------------------------------------------
    # 필요한 컬럼이 없으면 원래 컬럼명도 출력
    # 문제 발생 시 확인하기 쉬움
    # --------------------------------------------------------

    if missing_columns:

        print(
            f"  -> 제외됨. 자동 인식 실패 컬럼: "
            f"{missing_columns}"
        )

        print(
            f"  -> 실제 컬럼: "
            f"{original_columns}"
        )

        fail_count += 1

        continue


    # ========================================================
    # 8. 필요한 변수만 우선 선택
    # ========================================================

    df = df[
        [
            "지점",
            "일시",
            "기온",
            "풍속",
            "습도"
        ]
    ].copy()


    # ========================================================
    # 9. 자료형 변환
    # ========================================================

    # 일시
    df["일시"] = pd.to_datetime(
        df["일시"],
        errors="coerce"
    )


    # 지점
    df["지점"] = pd.to_numeric(
        df["지점"],
        errors="coerce"
    )


    # 기상 변수
    for column in [
        "기온",
        "풍속",
        "습도"
    ]:

        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )


    # ========================================================
    # 10. 지점 또는 날짜가 없는 행 제거
    # ========================================================

    before_count = len(df)

    df = df.dropna(
        subset=[
            "지점",
            "일시"
        ]
    ).copy()

    removed_count = (
        before_count - len(df)
    )

    if removed_count > 0:

        print(
            f"  -> 잘못된 지점/일시 "
            f"{removed_count:,}행 제거"
        )


    # ========================================================
    # 11. 지점번호 정수 처리
    # ========================================================

    df["지점"] = (
        df["지점"]
        .astype(int)
    )


    # ========================================================
    # 12. 같은 파일 안의 중복 제거
    #
    # 같은 지점 + 같은 일시가 2개 이상이면
    # 첫 번째 값 사용
    # ========================================================

    duplicate_count = (
        df.duplicated(
            subset=[
                "지점",
                "일시"
            ]
        )
        .sum()
    )


    if duplicate_count > 0:

        print(
            f"  -> 중복 "
            f"{duplicate_count:,}행 제거"
        )

        df = df.drop_duplicates(
            subset=[
                "지점",
                "일시"
            ],
            keep="first"
        )


    # ========================================================
    # 13. 지점 + 시간순 정렬
    # ========================================================

    df = df.sort_values(
        [
            "지점",
            "일시"
        ]
    )


    # ========================================================
    # 14. 지점별 3시간 평균기온 계산
    #
    # 중요:
    # 날짜를 자르기 전에 먼저 계산
    #
    # 따라서 5월 20일 00시의 평균 계산 시
    # 5월 19일 22시
    # 5월 19일 23시
    # 5월 20일 00시
    # 를 사용할 수 있음
    # ========================================================

    processed_groups = []

    for station, group in df.groupby(
        "지점",
        sort=False
    ):

        group = calculate_3hour_mean(
            group
        )

        processed_groups.append(
            group
        )


    df = pd.concat(
        processed_groups,
        ignore_index=True
    )


    # ========================================================
    # 15. 매년 5월 20일 00시 ~ 9월 25일 23시 추출
    # ========================================================

    month = df["일시"].dt.month
    day = df["일시"].dt.day


    date_condition = (

        # 5월 20일 ~ 5월 31일
        (
            (month == 5)
            &
            (day >= 20)
        )

        |

        # 6월 / 7월 / 8월
        month.isin(
            [6, 7, 8]
        )

        |

        # 9월 1일 ~ 9월 25일
        (
            (month == 9)
            &
            (day <= 25)
        )
    )


    df = df.loc[
        date_condition
    ].copy()


    # ========================================================
    # 16. 원본파일명 추가
    # ========================================================

    df["원본파일"] = (
        file.name
    )


    # ========================================================
    # 17. 저장할 컬럼
    # ========================================================

    df = df[
        [
            "지점",
            "일시",
            "기온",
            "풍속",
            "습도",
            "3시간평균기온",
            "원본파일"
        ]
    ]


    print(
        f"  -> 성공: "
        f"{len(df):,}행"
    )


    result_list.append(
        df
    )

    success_count += 1


# ============================================================
