# ============================================================
# 2. CSV 파일 자동 읽기
# ============================================================

def read_csv_auto(file_path):

    # 기상청 자료에서 주로 사용하는 인코딩 순서
    encodings = [
        "cp949",
        "utf-8-sig",
        "utf-8"
    ]

    for encoding in encodings:

        try:
            df = pd.read_csv(
                file_path,
                encoding=encoding
            )

            return df

        except UnicodeDecodeError:
            continue

    raise ValueError(
        f"인코딩을 확인할 수 없습니다: {file_path}"
    )


# ============================================================
# 3. 컬럼명 자동 인식 및 표준화
# ============================================================

def normalize_columns(df):

    # 앞뒤 공백 제거
    df.columns = (
        df.columns
        .astype(str)
        .str.strip()
    )

    rename_map = {}

    for col in df.columns:

        # 비교용 컬럼명
        clean_col = (
            str(col)
            .strip()
            .replace(" ", "")
        )

        # -----------------------------------------
        # 지점
        # -----------------------------------------
        if (
            clean_col == "지점"
            or "지점번호" in clean_col
            or "지점코드" in clean_col
        ):
            rename_map[col] = "지점"

        # -----------------------------------------
        # 일시
        # -----------------------------------------
        elif (
            clean_col == "일시"
            or clean_col == "시간"
            or "관측일시" in clean_col
        ):
            rename_map[col] = "일시"

        # -----------------------------------------
        # 기온
        #
        # 기온(℃)
        # 기온(°C)
        # 기온(C)
        # 모두 자동 인식
        # -----------------------------------------
        elif "기온" in clean_col:
            rename_map[col] = "기온"

        # -----------------------------------------
        # 풍속
        # -----------------------------------------
        elif "풍속" in clean_col:
            rename_map[col] = "풍속"

        # -----------------------------------------
        # 습도
        # -----------------------------------------
        elif "습도" in clean_col:
            rename_map[col] = "습도"

    df = df.rename(
        columns=rename_map
    )

    return df


# ============================================================
# 4. 정확한 연속 3시간 평균기온 계산
# ============================================================

def calculate_3hour_mean(group):

    # 지점 안에서 시간순 정렬
    group = (
        group
        .sort_values("일시")
        .copy()
    )

    # --------------------------------------------------------
    # 이전 1시간 / 이전 2시간 자료
    # --------------------------------------------------------

    temp_1 = group["기온"].shift(1)
    temp_2 = group["기온"].shift(2)

    time_1 = group["일시"].shift(1)
    time_2 = group["일시"].shift(2)


    # --------------------------------------------------------
    # 정확히 1시간 간격인지 확인
    # --------------------------------------------------------

    condition_1 = (
        group["일시"] - time_1
        == pd.Timedelta(hours=1)
    )

    condition_2 = (
        time_1 - time_2
        == pd.Timedelta(hours=1)
    )


    # --------------------------------------------------------
    # 기온값 자체가 모두 존재하는지도 확인
    # --------------------------------------------------------

    temperature_exists = (
        group["기온"].notna()
        & temp_1.notna()
        & temp_2.notna()
    )


    # --------------------------------------------------------
    # 연속된 3시간 + 기온값 존재
    # --------------------------------------------------------

    valid = (
        condition_1
        & condition_2
        & temperature_exists
    )


    # --------------------------------------------------------
    # 3시간 평균기온
    #
    # 예:
    # 08시 = 20
    # 09시 = 21
    # 10시 = 22
    #
    # 10시 3시간 평균 = 21
    # --------------------------------------------------------

    group["3시간평균기온"] = (
        temp_2
        + temp_1
        + group["기온"]
    ) / 3


    # 연속 3시간이 아니면 결측 처리
    group.loc[
        ~valid,
        "3시간평균기온"
    ] = pd.NA


    # 소수점 둘째 자리까지
    group["3시간평균기온"] = (
        group["3시간평균기온"]
        .round(2)
    )

    return group


